/*
 * mathc.c — Standalone Build-Time Source Compiler & Dependency-Resolved Linker
 *
 * Purpose:
 *   Build-time CLI utility that reads one or more `.math` extension source files
 *   in ANY order (no numerical filename prefixes required), compiles each file
 *   into `ExtBuildCtx` via `ext_compile_unit()`, links all modules in topological
 *   dependency order (`<[dep]`) via `ext_link_units()`, serializes the single
 *   unified `.mathc` binary image in memory via `ext_save_mathc_mem()`, and writes
 *   `<output_image>` and optionally the legacy embedded-array header (pass `-`
 *   to skip header emission — the engine no longer embeds the stdlib image).
 *
 * Usage:
 *   ./mathc <output_image> <output_header.h|-> <c_array_name> <source_file_1> [source_file_2 ...]
 */

#include "mem_arena.h"
#include "sym_table.h"
#include "ext_loader.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static MemArena    g_mem;
static SymTable    g_sym;
static ExtBuildCtx g_build;
static uint8_t     g_mathc_buf[MATHC_MAX_IMAGE_BYTES];

static char *read_file_text(const char *path) {
    FILE *fp = fopen(path, "rb");
    if (!fp) return NULL;
    fseek(fp, 0, SEEK_END);
    long sz = ftell(fp);
    fseek(fp, 0, SEEK_SET);
    if (sz < 0 || sz > 65535L) { fclose(fp); return NULL; }
    char *buf = (char *)malloc((size_t)sz + 1);
    if (!buf) { fclose(fp); return NULL; }
    size_t n = fread(buf, 1, (size_t)sz, fp);
    buf[n] = '\0';
    fclose(fp);
    return buf;
}

static bool write_c_header(const char *header_path, const char *array_name,
                           const uint8_t *data, size_t len) {
    FILE *out = fopen(header_path, "wb");
    if (!out) return false;

    const char *base_name = header_path;
    const char *slash     = strrchr(header_path, '/');
    const char *bslash    = strrchr(header_path, '\\');
    if (slash && slash + 1 > base_name)   base_name = slash + 1;
    if (bslash && bslash + 1 > base_name) base_name = bslash + 1;

    fprintf(out,
            "/*\n"
            " * %s — Auto-Generated Precompiled Standard Library Binary Image\n"
            " *\n"
            " * Generated by `mathc` (%zu bytes total).\n"
            " * Embedded directly into `math_engine.c` so `eng_init()` boots in O(1)\n"
            " * `memcpy` time with zero filesystem, directory, or file extension access.\n"
            " */\n\n"
            "#ifndef STDLIB_PRECOMPILED_H\n"
            "#define STDLIB_PRECOMPILED_H\n\n"
            "#include <stdint.h>\n"
            "#include <stddef.h>\n\n"
            "static const uint8_t %s[%zu] = {\n",
            base_name, len, array_name, len);

    for (size_t i = 0; i < len; ++i) {
        if (i % 12 == 0) fprintf(out, "    ");
        fprintf(out, "0x%02X%s", data[i], (i + 1 < len) ? "," : "");
        if (i % 12 == 11 || i + 1 == len) fprintf(out, "\n");
        else fprintf(out, " ");
    }

    fprintf(out,
            "};\n\n"
            "#endif /* STDLIB_PRECOMPILED_H */\n");
    fclose(out);
    return true;
}

int main(int argc, char **argv) {
    if (argc < 5) {
        fprintf(stderr,
                "Usage: %s <output_image> <output_header.h|-> <array_name> <source_file_1> [source_file_2 ...]\n",
                argv[0]);
        return 1;
    }

    const char *out_mathc = argv[1];
    const char *out_hdr   = (strcmp(argv[2], "-") == 0) ? NULL : argv[2];
    const char *arr_name  = argv[3];

    mem_init(&g_mem);
    sym_init(&g_sym);
    ext_build_init(&g_build);

    /* Phase 1: Compile (stage module units & dependencies from each input file in any order) */
    for (int i = 4; i < argc; ++i) {
        char *raw_text = read_file_text(argv[i]);
        if (!raw_text) {
            fprintf(stderr, "mathc error: cannot read '%s'\n", argv[i]);
            return 1;
        }
        bool ok = ext_compile_unit(&g_mem, &g_sym, &g_build, raw_text);
        free(raw_text);
        if (!ok) {
            fprintf(stderr, "mathc compile error in '%s': %s\n", argv[i], g_mem.err_msg);
            return 1;
        }
    }

    /* Phase 2: Link (topologically sort `<[dep]` graph and compile all modules into unified image) */
    if (!ext_link_units(&g_mem, &g_sym, &g_build)) {
        fprintf(stderr, "mathc link error: %s\n", g_mem.err_msg);
        return 1;
    }

    size_t mathc_bytes = ext_save_mathc_mem(&g_mem, &g_sym, g_mathc_buf, sizeof(g_mathc_buf));
    if (mathc_bytes == 0) {
        fprintf(stderr, "mathc serialize error: %s\n", g_mem.err_msg);
        return 1;
    }

    FILE *fp = fopen(out_mathc, "wb");
    if (!fp || fwrite(g_mathc_buf, 1, mathc_bytes, fp) != mathc_bytes) {
        if (fp) fclose(fp);
        fprintf(stderr, "mathc error: failed to write '%s'\n", out_mathc);
        return 1;
    }
    fclose(fp);

    printf("[mathc] Compiled & linked %d source file(s) (%u module units) -> '%s' (%zu bytes: %u modules, %u types, %u overloads, %u AST nodes)\n",
           argc - 4, (unsigned)g_build.unit_count, out_mathc, mathc_bytes,
           g_sym.mod_count, g_sym.type_count - 1, g_sym.overload_count, g_mem.perm_ast_count);

    if (out_hdr) {
        if (!write_c_header(out_hdr, arr_name, g_mathc_buf, mathc_bytes)) {
            fprintf(stderr, "mathc error: failed to export C header '%s'\n", out_hdr);
            return 1;
        }
        printf("[mathc] Exported embedded C header '%s' (array `%s`)\n", out_hdr, arr_name);
    }

    ext_build_free_heap(&g_build);
    sym_free_heap(&g_sym);
    return 0;
}
